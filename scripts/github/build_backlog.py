"""Render reviewable issue cards from the canonical backlog, without network calls."""

import argparse
import json
from pathlib import Path

from publish_issues import CATALOG, RECEIPT, render_body, validate_catalog


def outputs(catalog_path: Path) -> dict[Path, str]:
    catalog = json.loads(catalog_path.read_text())
    issues = validate_catalog(catalog)
    folder = catalog_path.parent
    receipt = json.loads(RECEIPT.read_text()) if RECEIPT.exists() else {}
    published = receipt.get("issues", {})
    completed = sum(issue.get("implementation_status") == "completed_locally" for issue in issues)
    completion_evidence = {
        issue["id"]: issue["completion_evidence"] for issue in issues
        if issue.get("implementation_status") == "completed_locally"
    }
    lines = [
        "# Ordered implementation backlog", "",
        (f"{len(issues)} bounded tasks for `{catalog['repository']}`. "
        "Stable IDs identify tasks; the **Order** column defines implementation sequence. "
        "Dependencies must be completed or explicitly unblocked before implementation."), "",
        (f"Current plan: **{len(issues) - completed} pending**, **{completed} completed locally**. "
        "Completed tasks retain their history and prerequisites but are not posted as new open issues."), "",
        ("The canonical source is `issues.json`. The `issues/` cards and this index "
        "are generated by `python3 scripts/github/build_backlog.py --write`. "
        "The cards are planned work, not evidence that the product features exist."), "",
        (f"GitHub publication: **{receipt.get('status', 'not_attempted')}**. "
        f"Confirmed issue links: **{len(published)}**. "
        "See `publication.json` for actual confirmed numbers and access blockers; "
        "local task cards are not open GitHub issues."), "",
        "## Contribution and review", "",
        ("Claim one ready task and use its current target paths. Submit a focused PR "
        "with observed validation results and a rollback plan. Other AI tools implement; "
        "the designated maintainer/assistant reviews the actual diff before an authorized "
        "merge. No self-merge or automatic mass merge is configured. "
        "An assistant review happens when a PR is brought into an active session; "
        "this repository does not provide continuous unattended assistant monitoring."), "",
        ("Owner decisions, paid infrastructure, data rights, provider activation and "
        "production release gates require their stated approvals. Later research tasks "
        "are optional and conditional, not promises of model breakthroughs."), "",
        "## Publication", "",
        ("`python3 scripts/github/publish_issues.py` validates offline. "
        "`python3 scripts/github/publish_issues.py --publish` reconciles existing remote "
        "markers and creates only missing issues using existing `gh` authentication. "
        "It never edits/closes existing issues and stops on ambiguous writes. "
        "The environment must allow `api.github.com`, and the existing GitHub identity "
        "must have issue-write permission. Never paste credentials into this catalogue."), "",
        "## Execution order", "",
        "| Order | Task | State | Priority | Area | Prerequisites |", "| --- | --- | --- | --- | --- | --- |",
    ]
    rendered = {}
    for issue in issues:
        identifier = issue["id"]
        dependencies = ", ".join(issue.get("depends_on", [])) or "None"
        title = issue["title"].replace("|", "\\|")
        lines.append(
            f"| {issue['order']} | [{identifier}: {title}](issues/{identifier}.md) "
            f"| {issue.get('implementation_status', 'planned')} "
            f"| {issue['priority']} | {issue['area']} | {dependencies} |"
        )
        rendered[folder / "issues" / f"{identifier}.md"] = (
            f"# [{identifier}] {issue['title']}\n\n"
            + render_body(issue, published, completion_evidence)
        )
    rendered[folder / "README.md"] = "\n".join(lines).rstrip() + "\n"
    return rendered


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, default=CATALOG)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = outputs(args.catalog)
    for path, content in rendered.items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        elif not path.exists() or path.read_text() != content:
            raise SystemExit(f"Backlog card/index is stale: {path.name}; regenerate from issues.json.")
    print(f"Backlog {'written' if args.write else 'checked'}: {len(rendered) - 1} issue cards; no network requests.")


if __name__ == "__main__":
    main()
